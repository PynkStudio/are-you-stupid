        case phonesUp, getReady, readTwice
        case noExcuses, go, doTheThing
        case liveRound, dontPanic, everyoneSees
        case chaosDirector, tvJudging, standings, moreRows
        // Results
        case everyoneRight, everyoneFailed, failedOfTotal
        case playerIsOut, playersAreOut, suspiciouslyCompetent, nobodyRead
        case hadOneJob, oneBraincell, mostlyStupid, mixedEmbarrassment
        case stillIn, nextRound, youHadOneJob, tooSlow, eliminated
        case gotItRight, fastestThumb, nobodyFailed
        // Final
        case final, roundsOne, pts, rightOfTotal, avg, lifeLeftOne, livesLeft
        case leastStupid, nobodySurvived, everyoneIsStupid, lastRoundTookOut
        case itsATie, equallyStupid, tiedOn
        case professionallyStupid, failOne, failsMany, onARoll, inARow
        case finalStandings, mostStupid, out
        case sponsors, adPressed, runItBack, anyPlayerRematch
    }

    public let locale: String

    public init(locale: String) {
        self.locale = Self.tables[locale] == nil ? "en" : locale
    }

    /// Looks up [key], substituting `{name}` placeholders from [args].
    public func callAsFunction(_ key: Key, _ args: [String: CustomStringConvertible] = [:]) -> String {
        var text = Self.tables[locale]?[key] ?? Self.tables["en"]?[key] ?? key.rawValue
        for (name, value) in args {
            text = text.replacingOccurrences(of: "{\(name)}", with: value.description)
        }
        return text
    }

    /// The host's fallback verdict reason (`RoomHost`, phone never answered)
    /// is wire text in English; show it in the board's language.
    public func failReason(_ raw: String) -> String {
        if raw.isEmpty { return self(.youHadOneJob) }
        let bare = raw.trimmingCharacters(in: CharacterSet(charactersIn: ". ")).lowercased()
        if bare == "too slow" { return self(.tooSlow) }
        return raw.uppercased()
    }

