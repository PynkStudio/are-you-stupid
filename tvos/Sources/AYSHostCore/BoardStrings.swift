//
//  BoardStrings.swift
//  AYSHostCore
//
//  Every piece of fixed board copy (lobby, round, results, final, options),
//  in the same six locales as the game and the presenter. The board speaks
//  the room's language: `HostViewModel` builds this from the presenter
//  locale, so one LANGUAGE choice drives voice, captions and screen text.
//  Unknown locales and missing keys fall back to English. Mode names
//  (STUPID BATTLE, LAST STUPID STANDING) and the brand stay English
//  everywhere, like on the phones. See docs/Architecture/Localization.md.
//

import Foundation

public struct BoardStrings: Sendable {
    public enum Key: String, CaseIterable, Sendable {
        // Lobby
        case partyPackActivated, partyPackBody, options
        case marqueeEmpty, marqueeOne, marqueeMany
        case phoneIsController, scanJoinPanic, orEnterCode
        case networkStarting, networkReady, networkUnavailable
        case whosIn, playersCount, playerSeat, ready, warmingUp
        case danceFloorEmpty, danceFloorHint
        case waitingTwoReady, oneMoreReady, partyReady, startChaos
        case roundsDetail, livesDetail
        // Options
        case language, languageNote, presenterOutput, outputNote
        case outputOff, outputMute, outputVoice
        case roastLevel, intensityNeutral, intensitySavage
