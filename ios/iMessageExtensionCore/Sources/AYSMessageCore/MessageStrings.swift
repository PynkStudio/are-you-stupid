import Foundation

/// The six game languages, mirrored from the Flutter app's `lib/i18n/`.
///
/// The extension follows the device language (it cannot read the app's
/// in-app setting); anything unsupported falls back to English. Challenge
/// copy reuses the app's own translations so a trap reads the same in
/// Messages as it does in the game.
public enum MessageLanguage: String, CaseIterable, Sendable {
    case en, it, fr, es, pt, de

    /// First supported language in the user's preference list.
    public static func preferred(_ identifiers: [String] = Locale.preferredLanguages) -> MessageLanguage {
        for identifier in identifiers {
            let code = identifier.lowercased().split(whereSeparator: { $0 == "-" || $0 == "_" }).first.map(String.init) ?? ""
            if let language = MessageLanguage(rawValue: code) { return language }
        }
        return .en
    }
}

